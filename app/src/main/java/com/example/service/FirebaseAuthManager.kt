package com.example.service

import android.content.Context
import android.util.Log
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.NoCredentialException
import com.example.R
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.Firebase
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.auth
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.tasks.await

object FirebaseAuthManager {
  private const val TAG = "FirebaseAuthManager"

  private val auth: FirebaseAuth?
    get() = try {
      Firebase.auth
    } catch (e: Exception) {
      Log.w(TAG, "FirebaseAuth not initialized in this environment: ${e.message}")
      null
    }

  val currentUser: FirebaseUser?
    get() = auth?.currentUser

  val currentUid: String
    get() = auth?.currentUser?.uid.orEmpty()

  val currentEmail: String
    get() = auth?.currentUser?.email.orEmpty()

  fun authStateChanges(): Flow<FirebaseUser?> = callbackFlow {
    val firebaseAuth = auth
    if (firebaseAuth == null) {
      trySend(null)
      awaitClose {}
      return@callbackFlow
    }
    val listener = FirebaseAuth.AuthStateListener { fa ->
      trySend(fa.currentUser)
    }
    firebaseAuth.addAuthStateListener(listener)
    awaitClose { firebaseAuth.removeAuthStateListener(listener) }
  }

  /**
   * default_web_client_id is only generated by the Google services plugin when google-services.json exists and has a
   * Web OAuth client. Looking it up by name keeps the project compiling without that file; Google Sign-In then
   * reports a clear message instead of the whole app failing to build.
   */
  private fun webClientIdOrThrow(context: Context): String {
    val resId = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
    val value = if (resId != 0) context.getString(resId) else ""
    check(value.isNotBlank()) { "Google Sign-In is not set up: google-services.json with a Web client ID is missing." }
    return value
  }

  /**
   * Explicit Google Sign-In button action using Jetpack Credential Manager.
   */
  suspend fun signInWithGoogleButton(activityContext: Context): Result<FirebaseUser> {
    return try {
      val webClientId = webClientIdOrThrow(activityContext)
      val signInOption = GetSignInWithGoogleOption.Builder(webClientId).build()
      val request = GetCredentialRequest.Builder()
        .addCredentialOption(signInOption)
        .build()
      executeCredentialRequest(activityContext, request)
    } catch (e: GetCredentialCancellationException) {
      Result.failure(Exception("Google Sign-In was cancelled."))
    } catch (e: Exception) {
      Log.w(TAG, "Google Sign-In failed: ${e.message}")
      Result.failure(e)
    }
  }

  /**
   * Silent / returning user Google Sign-In check via Credential Manager.
   */
  suspend fun trySilentGoogleSignIn(activityContext: Context): Result<FirebaseUser> {
    val existing = currentUser
    if (existing != null) return Result.success(existing)
    return try {
      val webClientId = webClientIdOrThrow(activityContext)
      val googleIdOption = GetGoogleIdOption.Builder()
        .setServerClientId(webClientId)
        .setFilterByAuthorizedAccounts(true)
        .setAutoSelectEnabled(true)
        .build()
      val request = GetCredentialRequest.Builder()
        .addCredentialOption(googleIdOption)
        .build()
      executeCredentialRequest(activityContext, request)
    } catch (e: NoCredentialException) {
      Result.failure(e)
    } catch (e: Exception) {
      Result.failure(e)
    }
  }

  /**
   * Signs in with a custom token issued by the trusted NFL security backend.
   */
  suspend fun signInWithBackendCustomToken(customToken: String): Result<FirebaseUser> {
    if (customToken.isBlank()) {
      return Result.failure(IllegalArgumentException("Custom token is blank"))
    }
    val firebaseAuth = auth ?: return Result.failure(IllegalStateException("FirebaseAuth unavailable"))
    return try {
      val authResult = firebaseAuth.signInWithCustomToken(customToken).await()
      val user = authResult.user
      if (user != null) {
        Result.success(user)
      } else {
        Result.failure(IllegalStateException("Custom token sign-in returned null user"))
      }
    } catch (e: Exception) {
      Log.w(TAG, "Custom token sign-in failed: ${e.message}")
      Result.failure(e)
    }
  }

  /** Result of an employee sign-in or account creation. The message is safe to show on screen. */
  sealed class EmployeeAuthResult {
    data class Success(val user: FirebaseUser) : EmployeeAuthResult()
    data class Failure(val message: String, val alreadyExists: Boolean = false) : EmployeeAuthResult()
  }

  /** The hidden Firebase e-mail of an employee. It is never shown and never receives mail. */
  fun employeeEmail(employeeId: String): String =
    employeeId.trim().lowercase(java.util.Locale.US) + "@staff.nfl-live.app"

  suspend fun signInEmployee(employeeId: String, password: String): EmployeeAuthResult =
    signInWithEmailInternal(employeeEmail(employeeId), password)

  /** For the project owner only: signs in with a real e-mail address. */
  suspend fun signInWithEmail(email: String, password: String): EmployeeAuthResult =
    signInWithEmailInternal(email.trim(), password)

  private suspend fun signInWithEmailInternal(email: String, password: String): EmployeeAuthResult {
    val firebaseAuth = auth ?: return EmployeeAuthResult.Failure("Cloud sign-in is not available on this device.")
    return try {
      val user = firebaseAuth.signInWithEmailAndPassword(email, password).await().user
      if (user != null) EmployeeAuthResult.Success(user) else EmployeeAuthResult.Failure("Sign-in failed. Please try again.")
    } catch (e: com.google.firebase.FirebaseNetworkException) {
      EmployeeAuthResult.Failure("No internet connection. Signing in needs internet.")
    } catch (e: com.google.firebase.FirebaseTooManyRequestsException) {
      EmployeeAuthResult.Failure("Too many attempts. Wait a few minutes and try again.")
    } catch (e: com.google.firebase.auth.FirebaseAuthInvalidCredentialsException) {
      EmployeeAuthResult.Failure("Employee ID or password is not correct.")
    } catch (e: com.google.firebase.auth.FirebaseAuthInvalidUserException) {
      EmployeeAuthResult.Failure("Employee ID or password is not correct.")
    } catch (e: com.google.firebase.auth.FirebaseAuthException) {
      // Not a wrong password: show the real reason so it can be fixed.
      EmployeeAuthResult.Failure("Sign-in could not be completed (${e.errorCode}).")
    } catch (e: Exception) {
      Log.w(TAG, "Email sign-in failed: ${e.message}")
      EmployeeAuthResult.Failure("Sign-in failed. Please check the internet and try again.")
    }
  }

  /**
   * Sends a password-reset link to a real e-mail address (the project owner / Administrator).
   * Employee accounts have no mailbox: for them the Administrator resets the account.
   */
  suspend fun sendPasswordReset(email: String): String {
    val firebaseAuth = auth ?: return "Cloud is not available on this device."
    val clean = email.trim()
    if (!clean.contains("@")) return "Type your e-mail address in the Employee ID box first."
    return try {
      firebaseAuth.sendPasswordResetEmail(clean).await()
      "If this e-mail has an account, a password reset link was sent. Check your inbox and spam folder."
    } catch (e: com.google.firebase.FirebaseNetworkException) {
      "No internet connection. Try again."
    } catch (e: com.google.firebase.auth.FirebaseAuthInvalidCredentialsException) {
      "That e-mail address is not valid."
    } catch (e: Exception) {
      Log.w(TAG, "Password reset failed: ${e.message}")
      "Could not send the reset link. Try again later."
    }
  }

  /** Creates the Firebase account of a new employee. It has no access until the Administrator approves it. */
  suspend fun createEmployeeAccount(employeeId: String, password: String): EmployeeAuthResult {
    val firebaseAuth = auth ?: return EmployeeAuthResult.Failure("Cloud sign-in is not available on this device.")
    return try {
      val user = firebaseAuth.createUserWithEmailAndPassword(employeeEmail(employeeId), password).await().user
      if (user != null) EmployeeAuthResult.Success(user) else EmployeeAuthResult.Failure("Could not create the account. Please try again.")
    } catch (e: com.google.firebase.auth.FirebaseAuthUserCollisionException) {
      EmployeeAuthResult.Failure("This Employee ID already has an account. Sign in instead. If you forgot the password, ask the Administrator.", alreadyExists = true)
    } catch (e: com.google.firebase.auth.FirebaseAuthWeakPasswordException) {
      EmployeeAuthResult.Failure("The password is too weak. Use at least 6 characters.")
    } catch (e: com.google.firebase.FirebaseNetworkException) {
      EmployeeAuthResult.Failure("No internet connection. Registering needs internet.")
    } catch (e: Exception) {
      Log.w(TAG, "Account creation failed: ${e.message}")
      EmployeeAuthResult.Failure("Could not create the account. Please check the internet and try again.")
    }
  }

  private suspend fun executeCredentialRequest(
    activityContext: Context,
    request: GetCredentialRequest
  ): Result<FirebaseUser> {
    val firebaseAuth = auth ?: return Result.failure(IllegalStateException("FirebaseAuth unavailable"))
    val credentialManager = CredentialManager.create(activityContext)
    val result = credentialManager.getCredential(activityContext, request)
    val credential = result.credential
    if (credential is CustomCredential &&
      credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
    ) {
      val googleIdTokenCredential = GoogleIdTokenCredential.createFrom(credential.data)
      val firebaseCredential = GoogleAuthProvider.getCredential(googleIdTokenCredential.idToken, null)
      val authResult = firebaseAuth.signInWithCredential(firebaseCredential).await()
      val user = authResult.user
      return if (user != null) {
        Result.success(user)
      } else {
        Result.failure(IllegalStateException("Firebase signInWithCredential returned null user"))
      }
    }
    return Result.failure(IllegalStateException("Unsupported credential type"))
  }

  suspend fun signOut(context: Context) {
    try {
      CredentialManager.create(context).clearCredentialState(ClearCredentialStateRequest())
    } catch (e: Exception) {
      Log.w(TAG, "ClearCredentialState warning: ${e.message}")
    }
    try {
      auth?.signOut()
    } catch (e: Exception) {
      Log.w(TAG, "FirebaseAuth signOut warning: ${e.message}")
    }
  }
}
